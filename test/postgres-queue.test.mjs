import assert from 'node:assert/strict';
import { createHmac, randomBytes, randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';
import { accountKey, createAccountStore } from '../server/account-store.js';
import { createCheckout } from '../server/checkout.js';
import { proofLimit, seal, secret } from '../server/common.js';
import { database } from '../server/database.js';
import { createQueueWorker } from '../server/order-queue.js';
import { createOrderQueue } from '../server/queue-store.js';
import { googleFixture } from './google-fixture.mjs';

const target = process.env.MARC_TEST_DATABASE_URL;

test('PostgreSQL admits 50 simultaneous full-size proofs, then releases them after saving', {
  skip: !target,
  timeout: 120000
}, async (t) => {
  const address = new URL(target);
  assert.ok(['127.0.0.1', 'localhost', '[::1]'].includes(address.hostname), 'Use a local test database.');
  const admin = database({ DATABASE_URL: address.href });
  const name = 'marc_test_' + randomUUID().replaceAll('-', '');
  await admin.query('CREATE DATABASE ' + name);
  address.pathname = '/' + name;
  const f = googleFixture();
  const env = { ...f.env, MARC_ORDER_QUEUE_ENABLED: '1', DATABASE_URL: address.href };
  const pool = database(env);
  t.after(async () => {
    await pool.end();
    // Removing the throwaway database drops only the data generated by this test.
    try { await admin.query('DROP DATABASE ' + name); } finally { await admin.end(); }
  });

  await pool.query(await readFile(new URL('../database/schema.sql', import.meta.url), 'utf8'));
  const queue = createOrderQueue(env, pool);
  const accounts = createAccountStore(env, f.fetcher, pool);
  const checkout = createCheckout({ env, fetcher: f.fetcher, queue, accounts });
  const worker = createQueueWorker({ env, queue });
  f.script.checkOrderStorage();
  f.state.deployed = f.catalogue();
  const origin = env.MARC_SITE_URL;
  const sub = 'test-buyer', sessionId = secret();
  const owner = accountKey(env, { sub });
  const session = await accounts.write('session', owner, { id: sessionId });
  const cookie = '__Host-marc-vercel-user=' + seal({
    sub, sessionId, googleEmail: true, name: 'Test Buyer', email: 'test@iimtrichy.ac.in',
    expires: Date.now() + 3600000
  }, 'buyer session v3', env.MARC_SESSION_KEY);
  const initialBag = await accounts.write('bag', owner, { items: [['POLO-W-M', 2]] }, null);
  assert.deepEqual(await accounts.read('bag', owner), initialBag);
  assert.ok(await accounts.write('bag', owner, { items: [] }, initialBag.version));
  assert.equal(await accounts.write('bag', owner, { items: [] }, initialBag.version), false);
  const buyerPost = (action, data) => checkout(new Request(origin + '/api/checkout?action=' + action, {
    method: 'POST',
    headers: { cookie, origin, ...(data instanceof FormData ? {} : { 'content-type': 'application/json' }) },
    body: data instanceof FormData ? data : JSON.stringify(data)
  }));
  const quoteFields = () => ({
    id: randomUUID(), version: f.state.deployed.version, items: [{ sku: 'POLO-W-M', qty: 1 }],
    contact: { name: 'Test Buyer', phone: '9876543210', roll: '0260010', affiliation: 'PGPM 2026-28' }
  });
  async function quote() {
    const response = await buyerPost('quote', quoteFields());
    assert.equal(response.status, 200);
    return response.json();
  }

  const bytes = randomBytes(proofLimit);
  Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]).copy(bytes);
  const proof = new Blob([bytes], { type: 'image/png' });
  function orderForm(order, index) {
    const form = new FormData();
    form.set('quote', order.token);
    form.set('utr', String(220000000000 + index));
    form.set('paidWith', 'GPay');
    form.set('proof', proof, 'proof.png');
    return form;
  }

  const orders = await Promise.all(Array.from({ length: 50 }, quote));
  const started = performance.now();
  const responses = await Promise.all(orders.map((order, index) => buyerPost('place', orderForm(order, index))));
  const pending = await Promise.all(responses.map(async (response) => {
    const entry = await response.json();
    assert.equal(response.status, 202, JSON.stringify(entry));
    assert.equal(entry.status, 'processing');
    return entry;
  }));
  assert.equal(new Set(pending.map((entry) => entry.number)).size, 50);
  t.diagnostic('50 parallel 4 MiB requests accepted in ' + Math.round(performance.now() - started) + ' ms locally.');
  assert.equal(await queue.availableBytes(), (384 - 200) * 1024 * 1024);

  // Emulate an already-paid retry racing against the storage budget.
  const extras = await Promise.all([quote(), quote()]);
  await pool.query('UPDATE marc.queue_control SET max_proof_bytes = $1', [51 * proofLimit]);
  const cap = await Promise.all(extras.map((order, index) => buyerPost('place', orderForm(order, index + 50))));
  assert.deepEqual(cap.map((response) => response.status).sort(), [202, 503]);
  const same = await buyerPost('place', orderForm(orders[0], 0));
  assert.equal(same.status, 202);
  assert.equal((await same.json()).number, pending[0].number);
  assert.equal((await buyerPost('place', orderForm(orders[0], 100))).status, 409);

  const work = (data) => {
    const issuedAt = Date.now(), payload = JSON.stringify(data);
    const signature = createHmac('sha256', env.MARC_SCRIPT_SECRET)
      .update('MARC order queue\n' + issuedAt + '\n' + payload).digest('hex');
    return worker(new Request(origin + '/api/order-queue', {
      method: 'POST', body: JSON.stringify({ issuedAt, payload, signature }),
      headers: { 'content-type': 'application/json' }
    }));
  };
  const list = await work({ action: 'list' });
  assert.equal(list.status, 200);
  const { jobs } = await list.json();
  assert.equal(jobs.length, 51);
  for (const key of jobs) {
    const response = await work({ action: 'read', key });
    assert.equal(response.status, 200);
    const binary = new Uint8Array(await response.arrayBuffer());
    const job = f.script.queueJob_({ getContent: () => binary });
    assert.equal(job.bytes.length, proofLimit);
    const result = f.script.saveOrder_(f.props, job.order, job.bytes);
    assert.ok(result.ok);
    const ack = { action: 'finish', key, fingerprint: job.fingerprint, id: job.order.id, result };
    assert.equal((await work(ack)).status, 204);
    assert.equal((await work(ack)).status, 204);
  }
  assert.equal(await queue.availableBytes(), 51 * proofLimit);
  assert.equal(f.orders.rows.length - 1, 51);
  assert.equal(f.files.size, 51);
  assert.deepEqual((await queue.list()).jobs, []);
  assert.equal((await pool.query('SELECT COUNT(*)::integer AS count FROM marc.order_queue WHERE proof IS NOT NULL')).rows[0].count, 0);
  const receipt = await (await buyerPost('status', { quote: orders[0].token })).json();
  assert.equal(receipt.number, pending[0].number);
  assert.equal(receipt.status, 'under_review');
  const secondSession = await accounts.write('session', owner, { id: secret() });
  assert.equal(await accounts.remove('session', owner, session.version), false);
  assert.deepEqual(await accounts.read('session', owner), secondSession);
});
